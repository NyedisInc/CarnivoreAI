from pathlib import Path
import subprocess

REPO_ROOT = Path(__file__).resolve().parents[1]
WORK_SH = REPO_ROOT / ".claude" / "skills" / "work" / "work.sh"


def _run_provision(tmp_path, make_source=True):
    src_repo = tmp_path / "src-repo"
    (src_repo / "web").mkdir(parents=True)
    if make_source:
        nm = src_repo / "web" / "node_modules"
        nm.mkdir()
        (nm / "some-pkg").mkdir()
        (nm / "some-pkg" / "index.js").write_text("module.exports = 1;\n")

    wt = tmp_path / "worktree"
    (wt / "web").mkdir(parents=True)

    result = subprocess.run(
        ["bash", str(WORK_SH), "provision-node-modules", str(src_repo), str(wt)],
        capture_output=True,
        text=True,
        timeout=30,
    )
    return src_repo, wt, result


def test_provisions_a_real_directory_not_a_symlink(tmp_path):
    src_repo, wt, result = _run_provision(tmp_path)
    assert result.returncode == 0, result.stderr

    dst = wt / "web" / "node_modules"
    assert dst.exists(), "provisioning did not create web/node_modules"
    assert not dst.is_symlink(), (
        "web/node_modules came out a SYMLINK: this is exactly the defect "
        "issue #924 describes. npm ci would remove the symlink's TARGET "
        "(the main checkout's real node_modules) instead of only this "
        "worktree's own copy."
    )
    assert dst.is_dir()
    assert (dst / "some-pkg" / "index.js").read_text() == "module.exports = 1;\n"


def test_negative_control_a_hand_made_symlink_trips_the_same_check(tmp_path):
    src_repo = tmp_path / "src-repo"
    (src_repo / "web" / "node_modules").mkdir(parents=True)

    trap_wt_web = tmp_path / "trap-worktree" / "web"
    trap_wt_web.mkdir(parents=True)
    (trap_wt_web / "node_modules").symlink_to(src_repo / "web" / "node_modules")

    dst = trap_wt_web / "node_modules"
    assert dst.is_symlink(), "negative control setup itself is broken"


def test_no_source_node_modules_is_a_silent_noop(tmp_path):
    src_repo, wt, result = _run_provision(tmp_path, make_source=False)
    assert result.returncode == 0, result.stderr
    assert not (wt / "web" / "node_modules").exists()


def test_an_existing_destination_is_left_alone(tmp_path):
    src_repo, wt, result = _run_provision(tmp_path)
    dst = wt / "web" / "node_modules"
    assert dst.exists()
    marker = dst / "do-not-touch"
    marker.write_text("already provisioned")

    result2 = subprocess.run(
        ["bash", str(WORK_SH), "provision-node-modules", str(src_repo), str(wt)],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result2.returncode == 0, result2.stderr
    assert marker.exists(), "re-running provisioning clobbered an existing destination"


def test_a_symlinked_source_is_never_cloned(tmp_path):
    real_elsewhere = tmp_path / "real-elsewhere"
    real_elsewhere.mkdir()

    src_repo = tmp_path / "src-repo"
    (src_repo / "web").mkdir(parents=True)
    (src_repo / "web" / "node_modules").symlink_to(real_elsewhere)

    wt = tmp_path / "worktree"
    (wt / "web").mkdir(parents=True)

    result = subprocess.run(
        ["bash", str(WORK_SH), "provision-node-modules", str(src_repo), str(wt)],
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, result.stderr
    assert not (wt / "web" / "node_modules").exists(), (
        "a symlinked source must not be cloned or symlinked into the worktree"
    )


def test_both_skill_copies_stay_byte_identical():
    other = REPO_ROOT / ".agents" / "skills" / "work" / "work.sh"
    assert WORK_SH.read_text() == other.read_text(), (
        ".claude and .agents copies of work.sh have drifted"
    )
