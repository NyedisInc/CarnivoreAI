
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Dict, List, Optional

WORKING_DIR = "/tmp/lineage-proj"
A_ID = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa"
B_ID = "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb"
C_ID = "cccccccc-cccc-cccc-cccc-cccccccccccc"

CAVEAT = "<local-command-caveat>Caveat: generated by the user while running local commands.</local-command-caveat>"


def user(text: str, ts: str, *, meta: bool = False, **extra: Any) -> Dict[str, Any]:
    record: Dict[str, Any] = {"type": "user", "timestamp": ts, "message": {"role": "user", "content": text}}
    if meta:
        record["isMeta"] = True
    record.update(extra)
    return record


def normal_lines(prompt: str = "fix the parser", ts: str = "2026-09-01T10:00:00Z") -> List[Dict[str, Any]]:
    return [user(prompt, ts), {"type": "assistant", "message": {"role": "assistant", "content": "ok"}}]


def command_lines(command: str = "/clear", prompt: str = "next task", ts: str = "2026-09-02T09:00:00Z") -> List[Dict[str, Any]]:
    name = command.lstrip("/")
    return [
        user(CAVEAT, ts, meta=True),
        user(f"<command-name>{command}</command-name>\n<command-message>{name}</command-message>\n<command-args></command-args>", ts),
        user("<local-command-stdout></local-command-stdout>", ts),
        user(prompt, ts),
    ]


def fork_lines(parent: str, prompt: str = "branch off", ts: str = "2026-09-02T09:00:00Z") -> List[Dict[str, Any]]:
    return [user(prompt, ts, forkedFrom={"sessionId": parent, "messageUuid": "m1"})]


def write_transcript(corpus: Path, conversation_id: str, lines: List[Dict[str, Any]], *, mtime: Optional[float] = None,
                     working_dir: str = WORKING_DIR) -> Path:
    from src.core.claude_transcript_correlate import slugify_project_dir

    folder = corpus / slugify_project_dir(working_dir)
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{conversation_id}.jsonl"
    path.write_text("\n".join(json.dumps(x) for x in lines) + "\n", encoding="utf-8")
    if mtime is not None:
        os.utime(path, (mtime, mtime))
    return path
