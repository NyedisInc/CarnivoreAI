export function refusalKey(code) {
    const trimmed = typeof code === 'string' ? code.trim() : '';
    if (!trimmed) return SKILL_KEYS.refusedUnknown;
    if (!REFUSAL_CODES.has(trimmed)) return SKILL_KEYS.refusedUnrecognised;
    return 'skill.refused.' + trimmed;
}

export function refusalMessage(code, t) {
    const key = refusalKey(code);
    if (key === SKILL_KEYS.refusedUnrecognised) {
        return t(key, { code: String(code).trim() });
    }
    return t(key);
}

export function reviewLabel(status, t) {
    if (status === 'reviewed') return t(SKILL_KEYS.reviewReviewed);
    if (status === 'unavailable') return t(SKILL_KEYS.reviewUnavailable);
    return null;
}

export function reasonOf(error, t) {
    const message = error && typeof error === 'object' && 'message' in error
        ? String(error.message || '').trim()
        : '';
    return message || t(SKILL_KEYS.serverUnreachable);
}

