
'use strict';

const path = require('path');
const { shellSingleQuote } = require('./terminal-launcher');

const FORBIDDEN_TMUX_WORDS = Object.freeze([
  'new-session', 'start-server', 'kill-server', 'kill-session', 'respawn-pane', 'respawn-window', 'source-file',
]);

const DEFAULT_SOCKET_NAME = 'cloude';

const SOCKET_NAME_RE = /^[A-Za-z0-9_.-]{1,64}$/;

const MAX_TMUX_NAME_LENGTH = 200;

const MAX_LABEL_LENGTH = 120;

const RESIZE_ESCAPE = "'\\033[8;%s;%st'";

function isValidTmuxName(name) {
  return typeof name === 'string' && name.length > 0 && name.length <= MAX_TMUX_NAME_LENGTH && !name.includes('\0');
}

function isAbsolutePath(value) {
  return typeof value === 'string' && path.isAbsolute(value) && !value.includes('\0');
}

function readSocketName(configText) {
  if (!configText) return DEFAULT_SOCKET_NAME;
  let parsed;
  try {
    parsed = JSON.parse(configText);
  } catch (error) {
    console.warn('[tray-terminal] config.json is not valid JSON; using the default tmux socket:', error.message);
    return DEFAULT_SOCKET_NAME;
  }
  const name = parsed && typeof parsed.session === 'object' && parsed.session ? parsed.session.tmux_socket_name : null;
  return typeof name === 'string' && SOCKET_NAME_RE.test(name) ? name : DEFAULT_SOCKET_NAME;
}

function socketPath(socketName, uid, tmuxTmpdir) {
  const base = isAbsolutePath(tmuxTmpdir) ? tmuxTmpdir : '/tmp';
  return path.join(base, `tmux-${uid}`, socketName);
}

function printableLabel(label) {
  // eslint-disable-next-line no-control-regex
  return String(label == null ? '' : label).replace(/[\u0000-\u001f\u007f]/g, ' ').slice(0, MAX_LABEL_LENGTH);
}

function scriptPreamble() {
  return [
    '#!/bin/bash',
    'rm -f -- "$0"; rmdir -- "${0%/*}" 2>/dev/null',
    '# Generated by Carnivore for one use; it deleted itself above.',
  ];
}

function claudeFallbackLines(reason) {
  return [
    'printf \'%s\\n\' ' + shellSingleQuote(reason),
    'if [ ! -d "$FOLDER" ]; then',
    '  printf \'%s\\n\' "Carnivore: the folder $FOLDER is gone, so claude was not started. This is a plain shell in your home folder."',
    '  cd -- "$HOME_FOLDER" || exit 1',
    '  exec "$SHELL_BIN" -l',
    'fi',
    'cd -- "$FOLDER" || exit 1',
    'exec "$CLAUDE_BIN"',
  ];
}

function buildSessionScript(spec) {
  if (!isAbsolutePath(spec.folder)) throw new Error('the session folder is not an absolute path');
  if (spec.claudeBin !== 'claude' && !isAbsolutePath(spec.claudeBin)) throw new Error('claude path is not absolute');
  if (!isAbsolutePath(spec.homeFolder)) throw new Error('the home folder is not an absolute path');
  if (!isAbsolutePath(spec.shellBin)) throw new Error('the login shell is not an absolute path');
  const label = printableLabel(spec.label);
  const lines = scriptPreamble().concat([
    'unset TMUX TMUX_PANE',
    'FOLDER=' + shellSingleQuote(spec.folder),
    'HOME_FOLDER=' + shellSingleQuote(spec.homeFolder),
    'SHELL_BIN=' + shellSingleQuote(spec.shellBin),
    'CLAUDE_BIN=' + shellSingleQuote(spec.claudeBin),
  ]);
  const canAttach = spec.tmuxName !== null && spec.tmuxName !== undefined;
  if (canAttach) {
    if (!isValidTmuxName(spec.tmuxName)) throw new Error('the tmux session name is not usable');
    if (!isAbsolutePath(spec.socketPath)) throw new Error('the tmux socket path is not absolute');
    if (spec.tmuxBin !== null && !isAbsolutePath(spec.tmuxBin)) throw new Error('tmux path is not absolute');
    lines.push(
      'TMUX_BIN=' + shellSingleQuote(spec.tmuxBin || ''),
      'SOCKET=' + shellSingleQuote(spec.socketPath),
      'TARGET=' + shellSingleQuote('=' + spec.tmuxName),
      'tq() { "$TMUX_BIN" -f /dev/null -S "$SOCKET" "$@"; }',
      'if [ -n "$TMUX_BIN" ] && [ -x "$TMUX_BIN" ] && tq has-session -t "$TARGET" 2>/dev/null; then',
      '  if [ "$(tq display-message -p -t "$TARGET:" \'#{pane_dead}\' 2>/dev/null)" != "1" ]; then',
      '    SIZE=$(tq display-message -p -t "$TARGET:" \'#{window_height} #{window_width}\' 2>/dev/null)',
      '    ROWS=${SIZE% *}; COLS=${SIZE#* }',
      '    case "$ROWS$COLS" in ""|*[!0-9]*) ;; *) printf ' + RESIZE_ESCAPE + ' "$ROWS" "$COLS" ;; esac',
      '    printf \'%s\\n\' ' + shellSingleQuote(
        `Carnivore: ${label}. Detach with Ctrl-b d; closing this window leaves the session running.`
      ),
      '    exec "$TMUX_BIN" -f /dev/null -S "$SOCKET" attach-session' + (spec.readOnly ? ' -r' : '') + ' -t "$TARGET"',
      '  fi',
      'fi'
    );
  }
  if (spec.readOnly) {
    return lines.concat([
      'printf \'%s\\n\' ' + shellSingleQuote(`Carnivore: ${label} is not running in tmux, so there is nothing to watch.`),
      'exit 1',
      '',
    ]).join('\n');
  }
  const reason = canAttach
    ? `Carnivore: tmux is not running ${label}, so this is a plain claude outside Carnivore, in its folder.`
    : `Carnivore: ${label} has no live tmux session, so this is a plain claude outside Carnivore, in its folder.`;
  return lines.concat(claudeFallbackLines(reason), ['']).join('\n');
}

function attachCommand(spec) {
  if (!isValidTmuxName(spec.tmuxName)) throw new Error('the tmux session name is not usable');
  if (!isAbsolutePath(spec.socketPath)) throw new Error('the tmux socket path is not absolute');
  if (spec.tmuxBin !== null && spec.tmuxBin !== undefined && !isAbsolutePath(spec.tmuxBin)) throw new Error('tmux path is not absolute');
  const bin = spec.tmuxBin ? shellSingleQuote(spec.tmuxBin) : 'tmux';
  return `${bin} -f /dev/null -S ${shellSingleQuote(spec.socketPath)} attach-session -t ${shellSingleQuote('=' + spec.tmuxName)}`;
}

function buildAttachScript(spec) {
  const argv = spec.argv;
  const clean = Array.isArray(argv) && argv.length > 0
    && argv.every((part) => typeof part === 'string' && part.length > 0 && !part.includes('\0'));
  if (!clean || !isAbsolutePath(argv[0])) throw new Error('the attach command is not usable');
  const label = printableLabel(spec.label);
  return scriptPreamble().concat([
    'unset TMUX TMUX_PANE',
    isAbsolutePath(spec.tmuxTmpdir) ? 'export TMUX_TMPDIR=' + shellSingleQuote(spec.tmuxTmpdir) : 'unset TMUX_TMPDIR',
    'printf \'%s\\n\' ' + shellSingleQuote(`Carnivore: ${label}. Detach with Ctrl-b d; closing this window leaves the session running.`),
    'exec ' + argv.map(shellSingleQuote).join(' '),
    '',
  ]).join('\n');
}

function buildShellScript(spec) {
  if (!isAbsolutePath(spec.folder)) throw new Error('the folder is not an absolute path');
  if (!isAbsolutePath(spec.shellBin)) throw new Error('the login shell is not an absolute path');
  return scriptPreamble().concat([
    'unset TMUX TMUX_PANE',
    'cd -- ' + shellSingleQuote(spec.folder) + ' || exit 1',
    'exec ' + shellSingleQuote(spec.shellBin) + ' -l',
    '',
  ]).join('\n');
}

const PYCACHE_VARS = ['PYTHONPYCACHEPREFIX', 'PYTHONDONTWRITEBYTECODE'];

function buildOfflineTuiScript(spec) {
  if (!isAbsolutePath(spec.serverDir)) throw new Error('the server folder is not an absolute path');
  const payload = spec.payload || null;
  if (payload && !(isAbsolutePath(payload.python) && isAbsolutePath(payload.tmux))) {
    throw new Error('the payload paths are not absolute');
  }
  return scriptPreamble().concat([
    'unset TMUX TMUX_PANE',
    ...(payload ? ['export CARNIVORE_BUNDLED_TMUX=' + shellSingleQuote(payload.tmux)] : []),
    ...(payload ? Object.entries(spec.pycache || {}).filter(([k]) => PYCACHE_VARS.includes(k)).map(([k, v]) => 'export ' + k + '=' + shellSingleQuote(v)) : []),
    'cd -- ' + shellSingleQuote(spec.serverDir) + ' || exit 1',
    payload ? 'exec ' + shellSingleQuote(payload.python) + ' -m src.tui --offline' : 'exec ./venv/bin/python3 -m src.tui --offline',
    '',
  ]).join('\n');
}

module.exports = {
  FORBIDDEN_TMUX_WORDS,
  DEFAULT_SOCKET_NAME,
  SOCKET_NAME_RE,
  MAX_LABEL_LENGTH,
  isValidTmuxName,
  isAbsolutePath,
  readSocketName,
  socketPath,
  printableLabel,
  buildSessionScript,
  attachCommand,
  buildAttachScript,
  buildShellScript,
  buildOfflineTuiScript,
};
