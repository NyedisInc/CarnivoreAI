export const INSTANCE_KINDS: readonly InstanceKind[] = Object.keys(INSTANCE_META) as InstanceKind[];

export function isInstanceId(id: SlotId): id is InstanceId {
  return kindOf(id) !== null;
}

export function kindOf(id: SlotId): InstanceKind | null {
  if (typeof id !== 'string') return null;
  return INSTANCE_KINDS.find((kind) => id.startsWith(`${kind}:`)) ?? pluginKinds().find((kind) => id.startsWith(`${kind}:`)) ?? null;
}

export function instanceName(id: SlotId): string {
  const kind = kindOf(id);
  if (!kind) return '';
  const tail = id.slice(kind.length + 1);
  return tail === '@primary' ? '' : tail;
}

export function instanceId(kind: InstanceKind, sessionId: string): InstanceId {
  return `${kind}:${sessionId}` as InstanceId;
}

/* list, so the */
export function metaFor(id: SlotId, metas: MetaMap = META): CellMeta {
  const kind = kindOf(id);
  if (kind) {
    const base = INSTANCE_META[kind] ?? pluginKindMeta(kind);
    if (!base) throw new Error(`opscenter: no base record for instance kind ${kind}`);
    const name = kind === 'terminal' ? instanceName(id) : '';
    return {
      ...base,
      id,
      chrome: 'card',
      ...(name ? { titleName: name } : {}),
    };
  }
  const record = metas[id as CellId];
  if (!record) {
    if (isPluginSlot(id)) return { ...PENDING_PLUGIN_META, id };
    throw new Error(`opscenter: no meta for cell ${id}`);
  }
  return record;
}

