function texts(value: Value | undefined): string[] {
    if (value === undefined) return [];
    return typeof value === 'string' ? [value] : [value.one, value.other];
}

const WORD_FOR_ONE = ['publish.page.held.day_limit', 'publish.page.held.open_limit'];

describe('publish page catalog', () => {
    it('pins every mockup string verbatim (at least 40, covering the stage words, key, tabs, checks, buttons, held reasons)', () => {
        expect(MOCKUP.length).toBeGreaterThanOrEqual(40);
        const wrong = MOCKUP.filter(([k, v]) => JSON.stringify(catalog[k]) !== JSON.stringify(v)).map(([k]) => k);
        expect(wrong).toEqual([]);
    });

    it('pins the strings a binding decision introduces, each tagged with its source', () => {
        const wrong = DECISIONS.filter(([k, v]) => JSON.stringify(catalog[k]) !== JSON.stringify(v)).map(([k, , d]) => `${k} (${d})`);
        expect(wrong).toEqual([]);
        for (const d of ['D4', 'D5', 'D14', 'D27', 'D30', 'Q3', 'Q4']) expect(DECISIONS.some(([, , src]) => src === d)).toBe(true);
    });

    it('keeps the existing skill.publish.* keys the page calls at their text', () => {
        const wrong = EXISTING.filter(([k, v]) => catalog[k] !== v).map(([k]) => k);
        expect(wrong).toEqual([]);
    });

    it('has every key of the fixed families', () => {
        const missing = FIXED_FAMILIES.filter((k) => !(k in catalog));
        expect(missing).toEqual([]);
    });

    it('writes the four stage words and the twelve checks in the decided order', () => {
        expect(['submitted', 'in_review', 'approved', 'rejected'].map((s) => catalog[`publish.page.stage.${s}`])).toEqual(['submitted', 'in review', 'approved', 'rejected']);
        expect(GATE_IDS.map((g) => catalog[`publish.page.check.${g}.label`])).toEqual(['structure', 'schema', 'kind rules', 'identity', 'digest', 'static scans', 'secrets', 'license', 'dependencies', 'ai review', 'clean room', 'grade']);
    });

    it('has no en dash, em dash or emoji under publish.page. or publish.new.', () => {
        const bad = /[\u2013\u2014]|\p{Extended_Pictographic}/u;
        const own = Object.keys(catalog).filter((k) => k.startsWith('publish.page.') || k.startsWith('publish.new.'));
        expect(own.length).toBeGreaterThan(100);
        const offenders = own.filter((k) => texts(catalog[k]).some((s) => bad.test(s)));
        expect(offenders).toEqual([]);
    });

    it('never says sidecar, cplug or claude code plugin on the page', () => {
        const own = Object.keys(catalog).filter((k) => k.startsWith('publish.page.') || k.startsWith('publish.new.'));
        const keys = [...own, ...CALLED_SKILL_PUBLISH_KEYS.filter((k) => k !== 'skill.publish.kind.cplug' && k !== 'catalog.kind.cplug')];
        expect(CALLED_SKILL_PUBLISH_KEYS).not.toContain('skill.publish.kind.cplug');
        const offenders = keys.filter((k) => texts(catalog[k]).some((s) => /sidecar|cplug|claude code plugin/i.test(s)));
        expect(offenders).toEqual([]);
    });

    it('keeps the plural shape for every count form', () => {
        const plural = Object.keys(catalog).filter((k) => k.startsWith('publish.page.') && typeof catalog[k] !== 'string');
        expect(plural.length).toBeGreaterThan(10);
        for (const k of plural) {
            const v = catalog[k] as Plural;
            expect(Object.keys(v).sort()).toEqual(['one', 'other']);
            if (!WORD_FOR_ONE.includes(k)) expect(v.one).toContain('{count}');
            expect(v.other).toContain('{count}');
        }
    });
});
