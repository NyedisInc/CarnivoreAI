
from __future__ import annotations

WAIT_MIGRATION = (
    "CREATE TABLE item_waits ("
    "id INTEGER PRIMARY KEY AUTOINCREMENT, "
    "item_id INTEGER NOT NULL, "
    "waiting_on TEXT NOT NULL DEFAULT '', "
    "kind TEXT NOT NULL DEFAULT 'other', "
    "set_by TEXT NOT NULL DEFAULT '', "
    "set_at REAL NOT NULL, "
    "expect_by REAL NOT NULL, "
    "deadline REAL NOT NULL, "
    "extended INTEGER NOT NULL DEFAULT 0, "
    "extend_reason TEXT NOT NULL DEFAULT '', "
    "check_kind TEXT NOT NULL DEFAULT '', "
    "check_json TEXT NOT NULL DEFAULT '', "
    "check_runs INTEGER NOT NULL DEFAULT 0, "
    "check_last_at REAL, "
    "check_next_at REAL, "
    "check_result TEXT NOT NULL DEFAULT '', "
    "token_hash TEXT NOT NULL DEFAULT '', "
    "status TEXT NOT NULL DEFAULT 'active', "
    "legacy INTEGER NOT NULL DEFAULT 0, "
    "ended_at REAL, "
    "ended_note TEXT NOT NULL DEFAULT '');"
    "CREATE INDEX item_waits_item ON item_waits (item_id, status);"
    "CREATE INDEX item_waits_live ON item_waits (status, deadline) WHERE status IN ('active', 'escalated');"
    "INSERT INTO item_waits (item_id, set_by, set_at, expect_by, deadline, legacy) "
    "SELECT id, owner_session_key, CAST(strftime('%s', 'now') AS REAL), CAST(strftime('%s', 'now') AS REAL) + 86400, "
    "CAST(strftime('%s', 'now') AS REAL) + 129600, 1 FROM items "
    "WHERE state = 'waiting' AND deleted = 0 AND lane = 'task_manager' AND swarm_ref = '' "
    "AND NOT EXISTS (SELECT 1 FROM blockers b WHERE b.item_id = items.id AND b.cleared_at IS NULL) "
    "AND COALESCE((SELECT l.\"by\" FROM item_lineage l WHERE l.item_id = items.id AND l.to_state = 'waiting' ORDER BY l.id DESC LIMIT 1), 'owner') "
    "NOT IN ('owner', 'carnivore', 'swarm', 'auto_done') "
    "AND COALESCE((SELECT l.\"by\" FROM item_lineage l WHERE l.item_id = items.id AND l.to_state = 'waiting' ORDER BY l.id DESC LIMIT 1), 'owner') "
    "NOT LIKE 'agent:%';"
    "CREATE TRIGGER items_wait_ends AFTER UPDATE OF state ON items "
    "WHEN OLD.state = 'waiting' AND NEW.state != 'waiting' "
    "BEGIN UPDATE item_waits SET status = CASE WHEN NEW.state IN ('review', 'done') THEN 'settled' ELSE 'ended' END, token_hash = '', "
    "ended_at = CAST(strftime('%s', 'now') AS REAL) WHERE item_id = NEW.id AND status IN ('active', 'escalated'); END;"
    "CREATE TRIGGER items_wait_ends_on_delete AFTER UPDATE OF deleted ON items "
    "WHEN NEW.deleted = 1 "
    "BEGIN UPDATE item_waits SET status = 'ended', token_hash = '', ended_at = CAST(strftime('%s', 'now') AS REAL) "
    "WHERE item_id = NEW.id AND status IN ('active', 'escalated'); END;"
)
