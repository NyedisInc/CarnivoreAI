#!/usr/bin/env python3
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Sequence

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import card_samples  # noqa: E402
from src.core.native_push import payload_crypto  # noqa: E402
from src.core.notifications import card_contract as cc, catalog_lines, types  # noqa: E402

SWIFT_OUT = ROOT / "ios/Shared/Generated/NotifyContract.swift"
TS_OUT = ROOT / "web/src/lib/notify-card/contract.gen.ts"
FIXTURE_DIR = ROOT / "tests/fixtures/notify_cards"
VECTORS_OUT = ROOT / "ios/Shared/TestVectors/notify_payload_vectors.json"
HEADER = "GENERATED by scripts/notify/gen_contract.py from src/core/notifications/card_contract.py. Do not edit."

VECTOR_KEY = bytes(range(32))
VECTOR_DEVICE = "d_0123456789ab"
VECTOR_CAP = "A" * 43


def _q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _pascal(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def render_swift() -> str:
    kinds = ", ".join(cc.KINDS)
    out = [f"// {HEADER}", "import Foundation", "", "/// The 15 card shapes.", f"enum NotifyKind: String, CaseIterable {{ case {kinds} }}", "",
           "/// One notification action; `labelKey` is the static fallback label (the payload's `acts` carry the real ones).",
           "struct NotifyAction { let id: String; let labelKey: String; let faceId: Bool; let textInput: Bool; let foreground: Bool }", "",
           "enum NotifyContract {", f"    static let version = {cc.PAYLOAD_VERSION}", f"    static let maxPlaintextBytes = {payload_crypto.MAX_PLAINTEXT_BYTES}"]
    for key, value in cc.LIMITS.items():
        out.append(f"    static let limit{_pascal(key)} = {value}")
    out.append("    static let sounds = [" + ", ".join(_q(s) for s in cc.DEVICE_SOUNDS) + "]")
    out.append("    static let earcons = [" + ", ".join(_q(s) for s in cc.EARCONS) + "]")
    out.append("    static let levels: [String: String] = [" + ", ".join(f"{_q(k)}: {_q(v)}" for k, v in cc.LEVELS.items()) + "]")
    out.append("    static let payloadKeys = [" + ", ".join(_q(k) for k in cc.PAYLOAD_KEYS) + "]")
    out.append("    /// Default sound and urgency letter per kind.")
    out.append("    static let kindStyle: [NotifyKind: (sound: String, level: String)] = [")
    for k in cc.KINDS:
        s, lv = cc.KIND_STYLE[k]
        out.append(f"        .{k}: ({_q(s)}, {_q(lv)}),")
    out.append("    ]")
    out.append("    static func categoryId(_ kind: NotifyKind) -> String { \"carnivore.\" + kind.rawValue }")
    out.append("    static let actions: [NotifyKind: [NotifyAction]] = [")
    for k in cc.KINDS:
        items = ", ".join(
            f"NotifyAction(id: {_q(a.id)}, labelKey: {_q(a.label_key)}, faceId: {str(a.face_id).lower()}, "
            f"textInput: {str(a.text_input).lower()}, foreground: {str(a.foreground).lower()})" for a in cc.ACTIONS[k])
        out.append(f"        .{k}: [{items}],")
    out.append("    ]")
    out.append("    /// Registry type id to its default card kind; any type not listed is `.notice`.")
    out.append("    static let typeKinds: [String: NotifyKind] = [")
    for t in types.TYPES:
        out.append(f"        {_q(t.id)}: .{cc.kind_for_type(t.id)},")
    out.append("    ]")
    out.append("    static let stringKeys = [")
    out.extend(f"        {_q(k)}," for k in cc.STRING_KEYS)
    out.append("    ]")
    out.append("}")
    return "\n".join(out) + "\n"


def render_ts() -> str:
    def arr(items: Sequence[str]) -> str:
        return "[" + ", ".join(_q(i) for i in items) + "] as const"

    out = [f"// {HEADER}", "", f"export const KINDS = {arr(cc.KINDS)};", "export type NotifyKind = (typeof KINDS)[number];",
           f"export const PAYLOAD_VERSION = {cc.PAYLOAD_VERSION};", f"export const MAX_PLAINTEXT_BYTES = {payload_crypto.MAX_PLAINTEXT_BYTES};",
           f"export const SOUNDS = {arr(cc.SOUNDS)};", f"export const EARCONS = {arr(cc.EARCONS)};",
           "export type NotifySound = (typeof SOUNDS)[number];",
           f"export const LEVELS = {json.dumps(cc.LEVELS)} as const;", "export type NotifyLevelLetter = keyof typeof LEVELS;",
           f"export const LIMITS = {json.dumps(cc.LIMITS)} as const;", f"export const PAYLOAD_KEYS = {arr(cc.PAYLOAD_KEYS)};", "",
           "export interface NotifyAction { id: string; labelKey: string; faceId: boolean; textInput: boolean; foreground: boolean }",
           "export const ACTIONS: Record<NotifyKind, readonly NotifyAction[]> = {"]
    for k in cc.KINDS:
        items = ", ".join(f'{{ id: {_q(a.id)}, labelKey: {_q(a.label_key)}, faceId: {str(a.face_id).lower()}, '
                          f'textInput: {str(a.text_input).lower()}, foreground: {str(a.foreground).lower()} }}' for a in cc.ACTIONS[k])
        out.append(f"  {k}: [{items}],")
    out += ["};", "", "export const CARD_FIELDS: Record<NotifyKind, readonly string[]> = {"]
    out += [f"  {k}: {arr(cc.CARD_FIELDS[k])}," for k in cc.KINDS]
    out += ["};", "", "export const KIND_STYLE: Record<NotifyKind, { sound: NotifySound; level: NotifyLevelLetter }> = {"]
    out += [f'  {k}: {{ sound: {_q(cc.KIND_STYLE[k][0])}, level: {_q(cc.KIND_STYLE[k][1])} }},' for k in cc.KINDS]
    out += ["};", "", "export const TYPE_KIND: Record<string, NotifyKind> = {"]
    out += [f"  {_q(t.id)}: {_q(cc.kind_for_type(t.id))}," for t in types.TYPES]
    out += ["};", "", "/** Every catalog key the contract names. */", "export const STRING_KEYS = ["]
    out += [f"  {_q(k)}," for k in cc.STRING_KEYS]
    out += ["] as const;"]
    return "\n".join(out) + "\n"


def _word(kind: str) -> str:
    return catalog_lines.read_prefixed((f"notify.card.word.{kind}",))[f"notify.card.word.{kind}"]


def split_card(kind: str) -> tuple:
    s = card_samples.SAMPLES[kind]
    only = cc.FULL_ONLY.get(kind, ())
    return ({k: v for k, v in s["card"].items() if k not in only},
            {**{k: v for k, v in s["card"].items() if k in only}, **(s.get("full") or {})})


def sample_push(kind: str) -> Dict[str, Any]:
    s = card_samples.SAMPLES[kind]
    compact, full = split_card(kind)
    card = {"strip": [_word(kind), "" if kind in cc.STRIP_WITHOUT_AGENT else s["agent"], s["computer"]], "agent": s["agent"],
            "computer": s["computer"], "ts": "9:41", **compact}
    return cc.build_payload(
        kind=kind, type_id=s["type"], title=s["title"], body=s["body"], path="/sessions/ses_0123456789ab",
        thread="local|ses_0123456789ab", sub=s["sub"], cap=VECTOR_CAP if s["cap"] else None, ttl=1794000000 if s["cap"] else None,
        acts=[tuple(a) for a in s["acts"]], card=card, more=bool(full), media=s.get("media"))


def _huge_push() -> Dict[str, Any]:
    s = card_samples.SAMPLES["permission"]
    card = {"strip": ["permission", "x" * 40, "y" * 40], "agent": "x" * 40, "computer": "y" * 40, "ts": "9:41",
            "cmd": ["cd web && npm run build && ./scripts/check.sh --all"] * 12, "dir": "web/", "tool": "bash",
            "opts": [[c, "option " + c * 20, "d" * 80] for c in "abcd"]}
    return cc.build_payload(kind="permission", type_id=s["type"], title="t" * 200, body="b" * 900, path="/p" * 200,
                            thread="th" * 200, sub="s" * 200, cap=VECTOR_CAP, ttl=1794000000,
                            acts=[(f"opt.{i}", "label " * 20) for i in range(1, 9)], card=card)


def _settle_push(where: str) -> Dict[str, Any]:
    s = card_samples.SAMPLES["yesno"]
    return cc.build_payload(kind="yesno", type_id=s["type"], title=s["agent"], body=_settled_body(), path="/sessions/ses_0123456789ab",
                            thread="local|ses_0123456789ab", lv="p", snd="none", settle={"where": where, "agent": s["agent"], "working": False})


def _settled_body() -> str:
    return catalog_lines.read_prefixed(("native.notify.settled",))["native.notify.settled"]


def render_fixtures() -> Dict[Path, str]:
    files: Dict[Path, str] = {}
    for kind in cc.KINDS:
        push = sample_push(kind)
        body: Dict[str, Any] = {"kind": kind, "payload": push, "card": push.get("card")}
        if split_card(kind)[1]:
            body["full"] = {**(push.get("card") or {}), **split_card(kind)[1]}
        files[FIXTURE_DIR / f"{kind}.json"] = json.dumps(body, indent=2, ensure_ascii=False) + "\n"
    huge = _huge_push()
    cases = {
        "huge": {"note": "every field at its limit; the payload trims to fit and the card clips at 12 lines with open to read all",
                 "payload": huge, "clip_lines": cc.LIMITS["card_clip_lines"], "cmd_lines": cc.LIMITS["card_full_cmd_lines"]},
        "empty": {"note": "no open notification", "payload": None, "card": None},
        "settled": {"note": "R18: the settle push for an ask answered elsewhere; one per `where`, same collapse id as the ask, passive and silent",
                    "payloads": {w: _settle_push(w) for w in cc.SETTLE_WHERE}},
        "failed": {"note": "the extension ran past 30 s or the attachment failed: the OS shows its plain view with the v2 actions",
                   "payload": {k: v for k, v in sample_push("permission").items() if k not in ("card", "media")}},
    }
    for name, body in cases.items():
        files[FIXTURE_DIR / f"{name}.json"] = json.dumps(body, indent=2, ensure_ascii=False) + "\n"
    return files


def render_vectors() -> str:
    cases: List[Dict[str, str]] = []
    pushes = [(kind, sample_push(kind)) for kind in cc.KINDS] + [("huge", _huge_push())]
    for i, (name, push) in enumerate(pushes):
        nonce = bytes([i + 1]) * payload_crypto.NONCE_BYTES
        plain = cc.encode(push)
        blob = payload_crypto.seal(VECTOR_KEY, VECTOR_DEVICE, plain, nonce=nonce)
        cases.append({"name": name, "device_id": VECTOR_DEVICE, "key": VECTOR_KEY.hex(), "nonce": nonce.hex(),
                      "aad": payload_crypto.associated_data(VECTOR_DEVICE).hex(), "plaintext": plain.hex(), "ciphertext": blob.hex(),
                      "plaintext_utf8": plain.decode("utf-8")})
    doc = {"format": "carnivore apns payload v2: same blob layout as apns_payload_vectors.json; plaintext is the v2 JSON of docs/notify-cards.md",
           "cases": cases}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def generate() -> Dict[Path, str]:
    files = {SWIFT_OUT: render_swift(), TS_OUT: render_ts(), VECTORS_OUT: render_vectors()}
    files.update(render_fixtures())
    return files


def main(argv: Sequence[str]) -> int:
    files = generate()
    if "--check" in argv:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"stale: {p}")
        return 1 if stale else 0
    for p, t in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="utf-8")
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
