_HEX = re.compile(r"^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$")
HEADER = "// GENERATED by scripts/ios/gen-tokens.py from the web app's theme.json files and i18n catalog. Do not edit.\n"


class GenError(Exception):
    pass


def parse_hex(value: str, where: str) -> int:
    match = _HEX.match(str(value).strip())
    if not match:
        raise GenError(f"{where}: {value!r} is not a #rgb or #rrggbb color")
    digits = match.group(1)
    if len(digits) == 3:
        digits = "".join(ch * 2 for ch in digits)
    return int(digits, 16)


def load_themes(themes_dir: Path = THEMES_DIR, catalog_clone: Optional[Path] = None) -> List[dict]:
    paths = list(themes_dir.glob("*/theme.json"))
    if catalog_clone is not None:
        found = []
        for handle in ("carnivore", "nyedis"):
            found = list((catalog_clone / "themes" / handle).glob("*/theme.json"))
            if found:
                break
        if not found:
            raise GenError(f"no themes/carnivore/*/theme.json under {catalog_clone}: is it a catalog clone?")
        paths += found
    themes: List[dict] = []
    for path in sorted(paths, key=lambda p: p.parent.name):
        css = json.loads(path.read_text(encoding="utf-8")).get("cssVars", {})
        colors: Dict[str, int] = {}
        for role, var in ROLES.items():
            if var not in css:
                raise GenError(f"{path}: cssVars has no {var} (needed for {role})")
            colors[role] = parse_hex(css[var], f"{path} {var}")
        themes.append({"id": path.parent.name, "colors": colors})
    if DEFAULT_THEME not in {t["id"] for t in themes}:
        raise GenError(f"no {DEFAULT_THEME} theme under {themes_dir}")
    return themes


def is_dark(rgb: int) -> bool:
    r, g, b = (rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255 < 0.5


def render_palettes(themes: Sequence[dict]) -> str:
    fields = "\n".join(f"    let {role}: Color" for role in ROLES)
    rows = []
    for theme in themes:
        args = ", ".join(f"{role}: Color(hex: 0x{theme['colors'][role]:06X})" for role in ROLES)
        rows.append(f'        Palette(id: "{theme["id"]}", isDark: {str(is_dark(theme["colors"]["page"])).lower()}, {args}),')
    return (
        f"{HEADER}import SwiftUI\n\n"
        "extension Color {\n"
        "    /// A color from 0xRRGGBB.\n"
        "    init(hex: UInt32) {\n"
        "        self.init(red: Double((hex >> 16) & 255) / 255, green: Double((hex >> 8) & 255) / 255, blue: Double(hex & 255) / 255)\n"
        "    }\n}\n\n"
        "/// One shipped theme's colors, by role.\n"
        f"struct Palette {{\n    let id: String\n    let isDark: Bool\n{fields}\n}}\n\n"
        "enum Palettes {\n"
        f'    static let fallbackId = "{DEFAULT_THEME}"\n'
        "    static let all: [Palette] = [\n" + "\n".join(rows) + "\n    ]\n\n"
        "    /// The palette for a theme id, or the default theme's when the id is nil or unknown.\n"
        "    static func palette(id: String?) -> Palette {\n"
        "        all.first { $0.id == id } ?? all.first { $0.id == fallbackId }!\n"
        "    }\n}\n"
    )


def swift_name(key: str) -> str:
    parts = [p for part in key.split(".")[1:] for p in part.split("_")]
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def render_strings(strings: Dict[str, str]) -> str:
    missing = [k for k in REQUIRED_KEYS if k not in strings]
    if missing:
        raise GenError("catalog.en.js is missing keys: " + ", ".join(missing))
    lines = []
    for key in sorted(strings):
        text = strings[key].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        lines.append(f'    static let {swift_name(key)} = "{text}"')
    return (
        f"{HEADER}import Foundation\n\n"
        "enum Strings {\n" + "\n".join(lines) + "\n\n"
        "    /// Replaces each {name} in a template with its value.\n"
        "    static func fill(_ template: String, _ values: [String: String]) -> String {\n"
        "        values.reduce(template) { $0.replacingOccurrences(of: \"{\\($1.key)}\", with: $1.value) }\n"
        "    }\n}\n"
    )


def build(themes_dir: Path = THEMES_DIR, catalog: Path = CATALOG, catalog_clone: Optional[Path] = None) -> Dict[str, str]:
    return {
        "Palettes.swift": render_palettes(load_themes(themes_dir, catalog_clone)),
        "Strings.swift": render_strings(read_prefixed(("ios.",), catalog)),
    }


def main(argv: Sequence[str]) -> int:
    clone = os.environ.get("CARNIVORE_CATALOG_CLONE")
    if "--catalog-clone" in argv:
        index = argv.index("--catalog-clone") + 1
        if index >= len(argv):
            print("gen-tokens: --catalog-clone needs a path", file=sys.stderr)
            return 1
        clone = argv[index]
    try:
        files = build(catalog_clone=Path(clone) if clone else None)
    except GenError as exc:
        print(f"gen-tokens: {exc}", file=sys.stderr)
        return 1
    stale = [n for n, src in files.items() if not (OUT_DIR / n).is_file() or (OUT_DIR / n).read_text(encoding="utf-8") != src]
    if "--check" in argv:
        if stale:
            print("gen-tokens: out of date: " + ", ".join(stale), file=sys.stderr)
        return 1 if stale else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, src in files.items():
        (OUT_DIR / name).write_text(src, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
